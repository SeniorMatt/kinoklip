QStringList describeStandardActions(ActionRegistry& registry)
{
    QStringList unknown;
    for (const Description& entry : kDescriptions) {
        const QString id = QLatin1String(entry.id);
        if (!registry.contains(id)) {
            unknown.append(id);
            continue;
        }
        QAction* action = registry.action(id);
        if (action->statusTip().isEmpty())
            action->setStatusTip(translate(entry.text));
    }

    // Commands made in loops: one line each, with the number in it.
    const auto describeNumbered = [&registry](const char* prefix, int count, const QString& text) {
        for (int n = 1; n <= count; ++n) {
            const QString id = QLatin1String(prefix) + QString::number(n);
            if (registry.contains(id) && registry.action(id)->statusTip().isEmpty())
                registry.action(id)->setStatusTip(text.arg(n));
        }
    };
    constexpr int kMaxNumbered = 32;
    describeNumbered("timeline.target_video_", kMaxNumbered,
        QCoreApplication::translate(
            "kk::ActionDescriptions", "Makes video track V%1 the destination of source edits."));
    describeNumbered("timeline.target_audio_", kMaxNumbered,
        QCoreApplication::translate(
            "kk::ActionDescriptions", "Makes audio track A%1 the destination of source edits."));
    describeNumbered("timeline.auto_select_video_", kMaxNumbered,
        QCoreApplication::translate(
            "kk::ActionDescriptions", "Switches auto select on or off for video track V%1."));
    describeNumbered("timeline.auto_select_audio_", kMaxNumbered,
        QCoreApplication::translate(
            "kk::ActionDescriptions", "Switches auto select on or off for audio track A%1."));
    describeNumbered("multicam.angle_", kMaxNumbered,
        QCoreApplication::translate("kk::ActionDescriptions",
            "Cuts or switches the multicam clip under the playhead to angle %1 (see Cut Mode and "
            "Switch Mode)."));
    return unknown;
}

