#!/usr/bin/env python3
"""Writes docs/keymaps/vim-keys.md, the cheat sheet of the Vim keys, from the default key table
resources/vim/default.json, so the page cannot go stale.

    python3 scripts/vim-docs.py          # rewrites the page
    python3 scripts/vim-docs.py --check  # exits 1 when the page is out of date (ctest, CI)

Only the standard library is used.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "resources" / "vim" / "default.json"
OUT = ROOT / "docs" / "keymaps" / "vim-keys.md"

CONTEXT_TITLES = {
    "global": "Everywhere the Vim keys work",
    "timeline": "Timeline (and viewers)",
    "viewer": "Viewers only",
}
MODE_TEXT = {
    "n": "NORMAL",
    "v": "VISUAL",
    "nv": "NORMAL and VISUAL",
    "o": "after an operator",
    "vo": "VISUAL and after an operator",
    "nvo": "NORMAL, VISUAL and after an operator",
}


def cell(text):
    return text.replace("|", "\\|")


def key_text(keys):
    keys = keys.replace("|", "\\|")
    return "`" + keys.replace("`", "` `` `") + "`" if "`" in keys else "`" + keys + "`"


def build():
    doc = json.loads(SOURCE.read_text(encoding="utf-8"))
    bindings = doc["bindings"]
    out = [
        "# Vim keys",
        "",
        "Generated by `scripts/vim-docs.py` from `resources/vim/default.json`; do not edit by hand.",
        "Turn Vim mode on in Preferences > Keyboard or with Kinoklip > Vim Mode. Change any key in",
        "Keyboard Customization > Vim keys, with `:nmap` / `:nunmap`, or in the `vimrc` text file.",
        "",
        "`<leader>` is Space. `<C-r>` is Ctrl+R. A count goes in front (`5l`, `3dd`). Esc drops what was",
        "typed; `i` or `a` switches to INSERT, where the keyboard profile's own shortcuts work, Esc comes",
        "back. Keys match their place on the keyboard when the layout is not Latin (a Russian layout works",
        "without switching).",
        "",
        "The timeline is the buffer: time is the line (a column is a frame), the tracks are the lines (the",
        "top track first, video then audio), clips are words, gaps are white space. The cursor is the",
        "playhead on the cursor track. The grammar is Vim's: `[\"register][count]operator[count]motion` or",
        "`operator` + text object, for example `\"a3dw`, `d]]`, `yiw`, `cip`. An operator key typed twice",
        "(`dd`, `yy`, `cc`) works on the clip under the cursor. The operators are `d` (ripple delete), `c`",
        "(delete leaving a gap, then INSERT) and `y` (copy). The rows marked *after an operator* are the",
        "motions and text objects an operator accepts. `.` repeats the last change.",
        "",
    ]
    leader = [b for b in bindings if b["type"] != "group" and b["keys"].startswith("<leader>")]
    rest = [b for b in bindings if b["type"] != "group" and not b["keys"].startswith("<leader>")]
    groups = [b for b in bindings if b["type"] == "group"]

    def table(title, rows):
        if not rows:
            return
        out.extend([f"## {title}", "", "| Keys | Mode | What it does | Runs |", "|---|---|---|---|"])
        for b in rows:
            run = ", ".join(f"`{r}`" for r in b["run"])
            out.append(f"| {key_text(b['keys'])} | {MODE_TEXT[b['modes']]} | {cell(b['desc'])} | {run} |")
        out.append("")

    for context in ("global", "timeline", "viewer"):
        table(CONTEXT_TITLES[context], [b for b in rest if b["context"] == context])
    names = {g["keys"]: g["desc"] for g in groups}
    out.extend(["## Leader keys (Space, then...)", "", "| Keys | What it does | Runs |", "|---|---|---|"])
    last = None
    for b in leader:
        prefix = b["keys"][: len("<leader>") + 1]
        group = names.get(prefix)
        if group and group != last:
            out.append(f"| **{key_text(prefix)}** | **{cell(group)}** | |")
            last = group
        run = ", ".join(f"`{r}`" for r in b["run"])
        out.append(f"| {key_text(b['keys'])} | {cell(b['desc'])} | {run} |")
    out.append("")
    out.extend([
        "## The command line",
        "",
        "`:` opens the command line in the bottom row; Tab completes, Up and Down recall older lines,",
        "`q:` lists the history. Besides the commands of `kinoklip commands` (`:marker add --frame 120`)",
        "it takes `:w` `:q` `:q!` `:wq` `:x`, `:e {timeline or file}` `:enew` `:bn` `:bp` `:bd` `:b {n}` `:ls`,",
        "`:120` / `:+10` / `:$` / `:00:01:10:00` (go to a frame or timecode), `:page {name}`, `:undo` `:redo`",
        "`:history`, `:render` `:deliver`, `:action {id}`, `:help` `:cheat` `:noh` `:play`, `:export` `:import`,",
        "`:nmap {keys} {command}`, `:nunmap {keys}`, `:map` (lists your mappings), `:source` (reads the vimrc",
        "again) and `:set snap` / `linked` / `audioscrub` / `loop` / `leader=<Space>` / `timeoutlen=400` /",
        "`physicalkeys` / `novim`.",
        "A command is an action id (`edit.undo`), `vim:name`, or `:` and a command line (`:w<CR>`).",
        "",
        "## The vimrc file",
        "",
        "A text file, one command per line, `\"` starts a comment: `set leader=<Space>`,",
        "`set timeoutlen=400`, `nmap <leader>w :w<CR>`, `nmap Q edit.undo`, `nunmap <leader>x`.",
        "It lives in the Kinoklip configuration folder as `vimrc`, so a dotfiles manager such as GNU Stow",
        "can keep it. Its mappings win over the table and show read-only in the Vim keys tab.",
    ])
    return "\n".join(out) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/keymaps/vim-keys.md is out of date: run python3 scripts/vim-docs.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
