/// A 3D .cube LUT of size @p n: out = (g^0.8, b, r) (channels rotated, green lifted), over
/// the domain 0..1.
QByteArray rotatingCube(int n)
{
    QByteArray text = "# generated by test_videoeffects2\nTITLE \"rotate\"\nLUT_3D_SIZE "
        + QByteArray::number(n) + "\n";
    for (int b = 0; b < n; ++b) {
        for (int g = 0; g < n; ++g) {
            for (int r = 0; r < n; ++r) {
                const double fr = r / double(n - 1), fg = g / double(n - 1), fb = b / double(n - 1);
                text += QByteArray::number(std::pow(fg, 0.8), 'f', 6) + ' '
                    + QByteArray::number(fb, 'f', 6) + ' ' + QByteArray::number(fr, 'f', 6) + '\n';
            }
        }
    }
    return text;
}

/// A 1D .cube LUT: out = 1 - in per channel (a negative), red scaled by 0.5.
QByteArray negativeCube1d(int n)
{
    QByteArray text = "LUT_1D_SIZE " + QByteArray::number(n) + "\n";
    for (int i = 0; i < n; ++i) {
        const double v = 1.0 - i / double(n - 1);
        text += QByteArray::number(0.5 * v, 'f', 6) + ' ' + QByteArray::number(v, 'f', 6) + ' '
            + QByteArray::number(v, 'f', 6) + '\n';
    }
    return text;
}

bool writeFile(const QString& path, const QByteArray& bytes)
{
    QFile f(path);
    return f.open(QIODevice::WriteOnly) && f.write(bytes) == bytes.size();
}

/// Number of distinct colours on row @p y.
int distinctColors(const QImage& img, int y)
{
    std::set<QRgb> colors;
    for (int x = 0; x < img.width(); ++x)
        colors.insert(img.pixel(x, y));
    return int(colors.size());
}

double meanGrey(const QImage& img)
{
    double s = 0;
    for (int y = 0; y < img.height(); ++y)
        for (int x = 0; x < img.width(); ++x)
            s += qGray(img.pixel(x, y));
    return s / (img.width() * img.height());
}

double greySd(const QImage& img, const QRect& r)
{
    double s = 0, s2 = 0;
    int n = 0;
    for (int y = r.top(); y <= r.bottom(); ++y) {
        for (int x = r.left(); x <= r.right(); ++x) {
            const double g = qGray(img.pixel(x, y));
            s += g;
            s2 += g * g;
            ++n;
        }
    }
    const double m = s / n;
    return std::sqrt(std::max(0.0, s2 / n - m * m));
}

int maxDiff(const QImage& a, const QImage& b)
{
    int worst = 0;
    for (int y = 0; y < a.height(); ++y) {
        for (int x = 0; x < a.width(); ++x) {
            const QRgb p = a.pixel(x, y), q = b.pixel(x, y);
            worst = std::max({worst, std::abs(qRed(p) - qRed(q)), std::abs(qGreen(p) - qGreen(q)),
                std::abs(qBlue(p) - qBlue(q))});
        }
    }
    return worst;
}

