        const QImage clean = render(*m_gpu, noisy);
        const QRect area(20, 20, 120, 50);
        qInfo("noise reduction: sd %.2f -> %.2f", greySd(grain, area), greySd(clean, area));
        QVERIFY(greySd(clean, area) < 0.8 * greySd(grain, area));
        const QImage letter = letterWith(nullptr);
        TimelineData t3 = emptyTimeline();
