    // ---- Stylize ----

    void stylizeEffects()
    {
        if (!gpuReady())
            QSKIP("no OpenGL");
        if (!m_fixtureError.isEmpty())
            QSKIP(qPrintable(m_fixtureError));
        TimelineData t = emptyTimeline();
        const QImage plain = videoWith({});
        // Pixelate: cells of one colour (neighbours equal) on a noisy picture; dots show the
        // background between them.
        TimelineData n = emptyTimeline(320, 180);
        ClipData noise = solidClip(n, QColor(128, 128, 128), 0, 10);
        noise.effects.append(
            effect(n, fxid::FilmGrain, {{k::Amount, 60.0}}, {{k::Animated, false}}));
        addClip(n, TrackType::Video, 0, noise);
        auto equalNeighbours = [](const QImage& img) {
            int same = 0, total = 0;
            for (int y = 10; y < img.height() - 10; y += 7) {
                for (int x = 0; x + 1 < img.width(); ++x) {
                    same += img.pixel(x, y) == img.pixel(x + 1, y) ? 1 : 0;
                    ++total;
                }
            }
            return double(same) / total;
        };
        const double plainSame = equalNeighbours(render(*m_gpu, n));
        for (const QString& shape : {fxchoice::Hexagons, fxchoice::Diamonds}) {
            TimelineData c = n;
            c.videoTracks[0].clips[0].effects.append(
                effect(c, fxid::Pixelate, {{k::Size, 16.0}}, {{k::Shape, shape}}));
            const double same = equalNeighbours(render(*m_gpu, c));
            qInfo("pixelate %s: %.2f of the neighbours equal (plain %.2f)", qPrintable(shape), same,
                plainSame);
            QVERIFY(same > 0.85);
            QVERIFY(plainSame < 0.5);
        }
        const QImage dots = videoWith({effect(t, fxid::Pixelate, {{k::Size, 24.0}},
            {{k::Shape, fxchoice::Circles}, {k::BackgroundColor, QColor(255, 0, 255)}})});
        // The grid is centred on the clip: (320, 180) is a cell corner (between 4 dots).
        QVERIFY2(near(px(dots, 320, 180), 255, 0, 255, 255, 2), describe(px(dots, 320, 180)));
        // Halftone on mid grey: black and white dots, about half the area dark.
        TimelineData g = emptyTimeline(160, 90);
        ClipData grey = solidClip(g, QColor(128, 128, 128), 0, 10);
        grey.effects.append(effect(g, fxid::Halftone, {{k::Size, 8.0}}));
        addClip(g, TrackType::Video, 0, grey);
        const QImage ht = render(*m_gpu, g);
        int dark = 0, mid = 0;
        for (int y = 0; y < 90; ++y) {
            for (int x = 0; x < 160; ++x) {
                const int v = qGray(ht.pixel(x, y));
                dark += v < 60 ? 1 : 0;
                mid += v >= 60 && v <= 195 ? 1 : 0;
            }
        }
        qInfo("halftone: %d dark, %d antialiased of %d", dark, mid, 160 * 90);
        QVERIFY(dark > 160 * 90 / 4 && dark < 160 * 90 * 3 / 4);
        QVERIFY(mid < 160 * 90 / 4);
        // Scanlines: on grey, rows alternate dark / bright with the spacing.
        g.videoTracks[0].clips[0].effects = {effect(g, fxid::Scanlines, {{k::Amount, 100.0}})};
        const QImage lines = render(*m_gpu, g);
        QVERIFY(qGray(lines.pixel(50, 1)) < 20);
        QVERIFY(qGray(lines.pixel(50, 3)) > 120);
        QVERIFY(qGray(lines.pixel(50, 5)) < 20);
        // Pencil sketch: flat grey becomes paper white; the letter's edge a dark line.
        g.videoTracks[0].clips[0].effects = {effect(g, fxid::PencilSketch)};
        QVERIFY(qGray(render(*m_gpu, g).pixel(80, 45)) > 245);
        const QImage sk = videoWith({effect(t, fxid::PencilSketch)});
        int darkest = 255;
        for (int y = 0; y < 360; y += 4)
            for (int x = 0; x < 640; ++x)
                darkest = std::min(darkest, qGray(sk.pixel(x, y)));
        qInfo("pencil sketch: mean %.1f (plain %.1f), darkest line %d", meanGrey(sk),
            meanGrey(plain), darkest);
        QVERIFY(meanGrey(sk) > meanGrey(plain) + 20); // mostly paper
        QVERIFY2(darkest < 120, QByteArray::number(darkest)); // with dark lines
        // Abstraction: fewer colours, still the picture.
        // (Grey 110 lies in the middle of a tone step: the smoothed noise stays in it.)
        TimelineData painted = n;
        painted.videoTracks[0].clips[0].solidColor = QColor(110, 110, 110);
        painted.videoTracks[0].clips[0].effects.append(
            effect(painted, fxid::Abstraction, {{k::Edges, 0.0}}));
        const QImage abs = render(*m_gpu, painted);
        qInfo("abstraction: %.2f of the neighbours equal, %d colours on a row (grain %d)",
            equalNeighbours(abs), distinctColors(abs, 90), distinctColors(render(*m_gpu, n), 90));
        QVERIFY(equalNeighbours(abs) > 0.6);
        QVERIFY(std::abs(meanGrey(abs) - 110) < 20);
        // Outlines darken edges: the white letter on grey gets a dark rim.
        const EffectInstance outlined = effect(t, fxid::Abstraction, {{k::Edges, 100.0}});
        const QImage rim = letterWith(&outlined);
        int rimDark = 255;
        for (int x = 0; x < 320; ++x)
            if (qAlpha(rim.pixel(x, 90)) == 255)
                rimDark = std::min(rimDark, qGray(rim.pixel(x, 90)));
        QVERIFY2(rimDark < 200, QByteArray::number(rimDark));
        QVERIFY(meanGrey(videoWith({effect(t, fxid::Abstraction)})) > 0.7 * meanGrey(plain));
        // Prism: a white letter gets coloured fringes.
        const EffectInstance prism = effect(t, fxid::Prism, {{k::Amount, 16.0}});
        const QImage pr = letterWith(&prism);
        bool fringe = false;
        for (int x = 0; x < 320; ++x) {
            const QRgb p = pr.pixel(x, 90);
            fringe = fringe || std::abs(qRed(p) - qBlue(p)) > 60;
        }
        QVERIFY(fringe);
    }

